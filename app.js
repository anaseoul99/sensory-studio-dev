function esc(value) {
  return String(value ?? "")
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;");
}

function logicMap(work, found) {
  const matches = found.matches || [];
  const first = matches[0];
  const scentName = first ? first.nameEN : work.scent;
  const category = first && first.category ? first.category : "";
  const tags = found.tags && found.tags.length ? found.tags : String(work.tags || "").split(" · ").filter(Boolean);
  const seen = new Set();
  const also = [];
  matches.slice(1).forEach((match) => {
    if (!match || !match.nameEN || match.nameEN === scentName || seen.has(match.nameEN)) return;
    seen.add(match.nameEN);
    also.push(match);
  });
  const formula = `OR(\n${tags.map((tag) => `  REGEX_MATCH(LOWER({FrDesc}), "${String(tag).toLowerCase()}")`).join(",\n")}\n)`;
  const alsoBlock = also.length ? `
    <div class="logic-join" aria-hidden="true"></div>
    <div class="logic-node logic-also">
      <span>Data Result</span>
      <p class="logic-use">같은 검색에서 같이 걸린 향</p>
      <ul>
        ${also.map((match) => `<li><b>${esc(match.nameEN)}</b><em>${esc(match.category || "")}</em></li>`).join("")}
      </ul>
    </div>` : "";
  return `
    <div class="logic" aria-label="감각 변환">
      <div class="logic-node logic-read">
        <span>인상</span>
        <strong>${esc(work.read)}</strong>
      </div>
      <div class="logic-stem" aria-hidden="true"></div>
      <div class="logic-node">
        <span>Keyword</span>
        <div class="logic-chips">${tags.map((tag) => `<i>${esc(tag)}</i>`).join("")}</div>
      </div>
      <div class="logic-rail" aria-hidden="true"></div>
      <div class="logic-outs">
        <div class="logic-node logic-sound">
          <span>Sound</span>
          <strong>${esc(work.track)}</strong>
        </div>
        <div class="logic-node logic-motion">
          <span>Interaction</span>
          <strong>p5.js</strong>
        </div>
        <div class="logic-node logic-scent">
          <span>Olfactory</span>
          <strong>${esc(scentName)}</strong>
          ${category ? `<em>${esc(category)}</em>` : ""}
          <b class="logic-tool">DB</b>
        </div>
      </div>
      <div class="logic-hows">
        <p class="is-sound"><b>Sound</b>어울리는 느낌으로 골랐다. 음원의 주파수 대역별(Bass, Mid, Treble) 에너지를 추출하여, 크기(Scale), 회전(Rotate), 색상(Tint)에 실시간으로 동기화한다.<code>bass = fft.getEnergy("bass");
mid = fft.getEnergy("mid");
treble = fft.getEnergy("treble");

scale(map(bass, 0, 255, 1, 1.15));
rotate(
  angle + sin(frameCount * 0.04 * speed)
  * map(mid, 0, 255, 0, 0.15)
);
tint(255, map(treble, 0, 255, 180, 255));</code></p>
        <p class="is-db"><b>DB</b>추출한 시각 키워드와 DB 내 향료 메타데이터(FrDesc)를 정규표현식(Regex)으로 매칭한다.<code>${esc(formula)}</code>겹치는 키워드가 많거나 그림에서 비중이 큰 단어를 고르고, 비슷하면 무작위로 고른다.</p>
        ${work.id === "circle" ? `<p class="is-ref"><b>참조</b><a href="#/reference/golden">황금비율</a></p>` : ""}
      </div>
      ${alsoBlock}
    </div>`;
}

function lookup(id) {
  return scents[id] || { tags: [], matches: [] };
}

function hits(tags, frDesc) {
  const hay = String(frDesc || "").toLowerCase();
  return tags.filter((tag) => hay.includes(tag.toLowerCase()));
}

function route() {
  window.clearInterval(typeDetailLogic.timer);
  document.body.classList.remove("is-editing");
  const parts = (location.hash.replace(/^#/, "") || "/").split("/").filter(Boolean);
  const section = parts[0] || "project";
  const page = section === "person" || section === "work" || section === "reference" ? section : "project";
  document.body.dataset.page = page;
  const themeWork = section === "work" && parts[1] ? works.find((item) => item.id === parts[1]) : null;
  const themeId = themes.some((theme) => theme.id === parts[1]) ? parts[1] : themeWork ? themeWork.theme : "";
  if (themeId) document.body.dataset.theme = themeId;
  else delete document.body.dataset.theme;
  document.querySelectorAll("[data-nav]").forEach((link) => {
    if (link.dataset.nav === page) link.setAttribute("aria-current", "page");
    else link.removeAttribute("aria-current");
  });
  if (section === "work" && themes.some((theme) => theme.id === parts[1])) renderTheme(parts[1]);
  else if (section === "work" && parts[1]) renderDetail(parts[1]);
  else if (section === "work") renderWork();
  else if (section === "reference" && parts[1] === "golden") renderGolden();
  else if (section === "reference" && parts[1] === "irrational") renderIrrational();
  else if (section === "reference" && parts[1] === "interlude") renderInterlude();
  else if (section === "reference") renderReference();
  else if (section === "person") renderPerson();
  else renderProject();
  window.scrollTo(0, 0);
}

