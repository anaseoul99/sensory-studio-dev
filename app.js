function bindSoundModal(work, scent) {
  document.querySelector(".logic-modal")?.remove();
  const sound = document.querySelector(".detail .is-sound");
  const db = document.querySelector(".detail .is-db");
  if (!sound && !db) return;
  const modal = document.createElement("div");
  modal.className = "logic-modal";
  modal.innerHTML = `<div class="logic-modal-card" role="dialog" aria-modal="true">
    <div class="logic-modal-tools">
      <button class="tech-item" type="button" data-step="p5">${iconP5()}<span>p5.js</span></button>
      <button class="tech-item" type="button" data-step="airtable">${iconAirtable()}<span>Airtable</span></button>
      <button class="tech-item" type="button" data-step="audio">${iconAudio()}<span>Audio</span></button>
      <button class="tech-item" type="button" data-step="olfactory">${iconScent()}<span>Scent</span></button>
    </div>
    <div class="logic-modal-body"></div>
  </div>`;
  document.body.appendChild(modal);
  const card = modal.querySelector(".logic-modal-card");
  const tools = card.querySelector(".logic-modal-tools");
  const body = card.querySelector(".logic-modal-body");
  let timer = 0;
  const reduced = () => window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  const show = () => {
    if (modal.classList.contains("is-open")) return;
    if (reduced()) modal.classList.add("is-open");
    else window.requestAnimationFrame(() => modal.classList.add("is-open"));
  };
  const typeCode = () => {
    window.clearInterval(timer);
    const code = body.querySelector("code");
    if (!code) return;
    const full = code.dataset.full || code.textContent;
    code.dataset.full = full;
    if (reduced()) {
      code.textContent = full;
      code.classList.remove("is-typing");
      return;
    }
    code.textContent = "";
    code.classList.add("is-typing");
    let index = 0;
    timer = window.setInterval(() => {
      index += 1;
      code.textContent = full.slice(0, index);
      if (index >= full.length) {
        window.clearInterval(timer);
        code.classList.remove("is-typing");
      }
    }, 18);
  };
  const mark = (step) => {
    document.querySelectorAll(".process .tech-item, .logic-modal-tools .tech-item").forEach((item) => {
      item.classList.toggle("is-open", item.dataset.step === step);
    });
  };
  const openStep = (step, label) => {
    window.clearInterval(timer);
    tools.hidden = false;
    mark(step);
    body.innerHTML = popupBody(work, step, scent);
    card.setAttribute("aria-label", label || "");
    show();
  };
  const open = (panel) => {
    window.clearInterval(timer);
    tools.hidden = true;
    mark("");
    body.innerHTML = panel.dataset.source || panel.innerHTML;
    card.setAttribute("aria-label", panel.dataset.label || panel.querySelector("b")?.textContent || "");
    const code = body.querySelector("code");
    if (code) code.dataset.full = code.textContent;
    show();
    typeCode();
  };
  const close = () => {
    window.clearInterval(timer);
    body.querySelector("code")?.classList.remove("is-typing");
    mark("");
    modal.classList.remove("is-open");
  };
  const listen = (el, panel) => {
    el.addEventListener("click", (event) => {
      event.preventDefault();
      event.stopPropagation();
      open(panel);
    });
  };
  if (sound) {
    listen(sound, sound);
    document.querySelectorAll(".detail .logic-sound").forEach((el) => listen(el, sound));
  }
  if (db) listen(db, db);
  const choose = (button, event) => {
    event.preventDefault();
    event.stopPropagation();
    const already = button.classList.contains("is-open") && modal.classList.contains("is-open");
    if (already && button.closest(".process")) {
      close();
      return;
    }
    openStep(button.dataset.step, button.querySelector("span")?.textContent || "");
  };
  document.querySelectorAll(".process .tech-item, .logic-modal-tools .tech-item").forEach((button) => {
    button.addEventListener("click", (event) => choose(button, event));
  });
  modal.addEventListener("click", (event) => {
    if (event.target === modal) close();
  });
  if (bindSoundModal.onKey) document.removeEventListener("keydown", bindSoundModal.onKey);
  bindSoundModal.onKey = (event) => {
    if (event.key === "Escape") close();
  };
  document.addEventListener("keydown", bindSoundModal.onKey);
}

function typeDetailLogic() {
  window.clearInterval(typeDetailLogic.timer);
  const root = document.querySelector(".detail .logic");
  if (!root) return;
  root.querySelectorAll(".is-sound, .is-db").forEach((panel) => {
    panel.dataset.source = panel.innerHTML;
    const label = panel.querySelector("b")?.textContent || "";
    if (label) panel.dataset.label = label;
  });
  if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;
  const nodes = [];
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let current;
  while ((current = walker.nextNode())) {
    if (!current.textContent.trim()) continue;
    nodes.push({ node: current, full: current.textContent });
  }
  nodes.forEach(({ node }) => {
    node.textContent = "";
  });
  root.classList.add("is-typing");
  let index = 0;
  let cursor = 0;
  const paint = () => {
    root.querySelectorAll(".is-caret").forEach((el) => el.classList.remove("is-caret"));
    if (index >= nodes.length) {
      root.classList.remove("is-typing");
      window.clearInterval(typeDetailLogic.timer);
      return;
    }
    const item = nodes[index];
    cursor += 8;
    item.node.textContent = item.full.slice(0, cursor);
    item.node.parentElement?.classList.add("is-caret");
    if (cursor >= item.full.length) {
      item.node.textContent = item.full;
      index += 1;
      cursor = 0;
    }
  };
  typeDetailLogic.timer = window.setInterval(paint, 16);
}

